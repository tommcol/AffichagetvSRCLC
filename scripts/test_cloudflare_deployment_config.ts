import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createDeploymentConfig } from './configure-cloudflare.mjs';
import { readSharedAppData } from '../worker/appDataCoordinator';
import { getTelegramSecretToken } from '../worker/telegram';
const base = JSON.parse(readFileSync('wrangler.json', 'utf8'));
const env = { DEPLOY_WORKER_NAME:'club-example', DEPLOY_KV_NAMESPACE_ID:'1234567890abcdef1234567890abcdef', DEPLOY_R2_BUCKET_NAME:'example-media', DEPLOY_DO_MIGRATION_TAG:'existing-v1', DEPLOY_DO_INSTANCE_NAME:'existing-data', DEPLOY_TELEGRAM_SECRET_SUFFIX:':existing-suffix' };
const config = createDeploymentConfig(base, env);
assert.equal(config.name,env.DEPLOY_WORKER_NAME);
assert.equal(config.kv_namespaces[0].id,env.DEPLOY_KV_NAMESPACE_ID);
assert.equal(config.r2_buckets[0].bucket_name,env.DEPLOY_R2_BUCKET_NAME);
assert.equal(config.migrations[0].tag,env.DEPLOY_DO_MIGRATION_TAG);
assert.equal(config.vars.APP_DATA_INSTANCE_NAME,env.DEPLOY_DO_INSTANCE_NAME);
assert.equal(config.vars.TELEGRAM_SECRET_SUFFIX,env.DEPLOY_TELEGRAM_SECRET_SUFFIX);
assert.equal(base.kv_namespaces[0].id,'REMPLACER_PAR_VOTRE_ID_KV');
for (const name of Object.keys(env).filter(k=>k!=='DEPLOY_TELEGRAM_SECRET_SUFFIX')) assert.throws(()=>createDeploymentConfig(base,{...env,[name]:''}),new RegExp(name));
assert.throws(()=>createDeploymentConfig(base,{...env,DEPLOY_KV_NAMESPACE_ID:'placeholder'}));
let selected = '';
const storage:any = {APP_DATA_INSTANCE_NAME:'existing-data',APP_DATA_COORDINATOR:{idFromName:(name:string)=>{selected=name;return name;},get:()=>({fetch:async()=>new Response('{"version":9}')})}};
assert.equal(await readSharedAppData(storage),'{"version":9}');
assert.equal(selected,'existing-data');
delete storage.APP_DATA_INSTANCE_NAME;
await readSharedAppData(storage);
assert.equal(selected,'club-app-data');
const expected = await crypto.subtle.digest('SHA-256',new TextEncoder().encode('fake-token:existing-suffix'));
assert.equal(await getTelegramSecretToken('fake-token',':existing-suffix'),Array.from(new Uint8Array(expected),x=>x.toString(16).padStart(2,'0')).join(''));
assert.notEqual(await getTelegramSecretToken('fake-token'),await getTelegramSecretToken('fake-token',':existing-suffix'));
console.log('Private deployment: resources, migration, instance continuity, webhook compatibility and fail-closed validation OK');
