import assert from 'node:assert/strict';
import { parseCalendarRows, guessCalendarCategory, calendarRowToMatch, mergeExcelCalendar } from '../src/utils/excelMatchParser';
import { prepareExcelApiHandoff } from '../src/utils/calendarImportIdentity';
import { mergeMatchItems } from '../src/utils/ffbbMergeUtils';
const headers = ['Division', 'N° de match ', 'Equipe 1', 'Equipe 2', 'Date de rencontre', 'Heure', 'Salle', 'Score 1', 'Score 2', 'Forfait 1', 'Forfait 2'];
const table = [headers, ['DMU18-3-P2', '18', 'CLUB EXEMPLE - 1 (9)', 'AUTRE CLUB - 2 (4)', '08/11/2026', '00:00', 'Salle', '', '', 'Non', 'Non'], ['DFU13-3-P2', '18', 'VISITEURS - 1', 'CLUB EXEMPLE - 2', '15/11/2026', '14:30', 'Salle', '', '', 'Non', 'Non']];
const p = parseCalendarRows(table);
assert.equal(p.rows.length, 2);
assert.equal(p.rows[0].time, '');
assert.equal(p.rows[0].home, 'CLUB EXEMPLE - 1');
assert.equal(p.clubs[0], 'CLUB EXEMPLE');
assert.equal(guessCalendarCategory(p.rows[0], 'CLUB EXEMPLE', []), 'U18 M1');
assert.equal(guessCalendarCategory(p.rows[1], 'CLUB EXEMPLE', []), 'U13 F2');
const fixtures = p.rows.map(r => calendarRowToMatch(r, 'CLUB EXEMPLE', guessCalendarCategory(r, 'CLUB EXEMPLE', []), []));
assert.notEqual(fixtures[0].id, fixtures[1].id, 'Short numbers in different competitions must not collide');
let plan = mergeExcelCalendar([], [], fixtures);
assert.equal(plan.added, 2);
assert.equal(plan.matches.every(m => m.selectedForWeekend === false), true);
const again = mergeExcelCalendar(plan.matches, [], fixtures);
assert.equal(again.added, 0);
assert.equal(again.matches.length, 2);
const update = mergeExcelCalendar(plan.matches, [], [{ ...fixtures[0], time: '16:00' }]);
assert.equal(update.matches.find(m => m.id === fixtures[0].id)?.time, '16:00');
const excel = { ...fixtures[0], selectedForWeekend: true, isTimeManual: true };
const api = { ...fixtures[0], id: 'ffbb-900001', ffbbMatchNumber: 'FFBB-900001', calendarSource: undefined, calendarImport: undefined, teamHome: 'CLUB EXEMPLE', category: 'U18 Garçons 1', rawFfbbCategory: undefined, date: '2026-11-09', time: '17:00', gymnasium: 'Salle officielle' };
const handoff = prepareExcelApiHandoff([excel], [], [api], []);
assert.equal(handoff.matches[0].calendarSource, 'ffbb');
const merged = mergeMatchItems(handoff.matches, [api]);
assert.equal(merged.length, 1);
assert.equal(merged[0].time, '17:00');
assert.equal(merged[0].date, '2026-11-09');
assert.equal(merged[0].selectedForWeekend, true);
assert.equal(merged[0].calendarImport?.key, excel.calendarImport?.key);
const reimport = mergeExcelCalendar(merged, [], [excel]);
assert.equal(reimport.skipped, 1);
assert.equal(reimport.matches[0].time, '17:00');
assert.equal(prepareExcelApiHandoff([excel], [], [], []).matches[0].id, excel.id, 'Missing API response retains Excel');
const scored = { ...api, homeScore: 72, awayScore: 60, result: 'win' as const, status: 'finished' as const };
const scoredHandoff = prepareExcelApiHandoff([excel], [], [scored], [scored]);
assert.equal(scoredHandoff.matches.length, 0);
assert.equal(scoredHandoff.results.length, 1, 'Duplicated API representations must match once');
assert.equal(mergeMatchItems(scoredHandoff.results, [scored])[0].homeScore, 72);
const twoLegs = [api, { ...api, id: 'ffbb-900002', ffbbMatchNumber: 'FFBB-900002', date: '2026-12-01' }];
assert.equal(prepareExcelApiHandoff([excel], [], twoLegs, []).matches[0].calendarSource, 'excel', 'Ambiguous repeated pairing must not be guessed');
const exact = { ...api, date: excel.date };
assert.equal(prepareExcelApiHandoff([excel], [], [exact, twoLegs[1]], []).matches[0].calendarSource, 'ffbb');
assert.throws(() => parseCalendarRows([['Incorrect']]));
assert.ok(parseCalendarRows([headers, [...table[1].slice(0, 4), '31/02/2026', ...table[1].slice(5)]]).rows[0].error);
assert.ok(parseCalendarRows([headers, [...table[1].slice(0, 5), '25:12', ...table[1].slice(6)]]).rows[0].error);
assert.equal(guessCalendarCategory({ ...p.rows[0], division: 'CD - Coupe' }, 'CLUB EXEMPLE', []), '');
const numeric = parseCalendarRows([headers, ['DM4', '7', 'CLUB EXEMPLE - 1', 'AUTRE CLUB - 1', 46334, 0.5, 'Salle', '', '', 'Non', 'Non']]);
assert.equal(numeric.rows[0].time, '12:00');
assert.equal(numeric.rows[0].date, '2026-11-08');
const scoreRows = parseCalendarRows([headers, ['DM4', '7', 'CLUB EXEMPLE - 1', 'AUTRE CLUB - 1', '08/11/2026', '18:00', 'Salle', 0, 65, 'Non', 'Non']]);
assert.equal(calendarRowToMatch(scoreRows.rows[0], 'CLUB EXEMPLE', 'Seniors M1', []).result, 'loss');
console.log('Excel calendar: parsing, category/squad, repeat imports, API priority, reschedule, score transition, ambiguity and history OK');
