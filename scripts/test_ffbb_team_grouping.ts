import assert from 'node:assert/strict';
import { groupFfbbTeams } from '../src/utils/ffbbTeamGrouping';
import type { FFBBTeamItem } from '../src/types';
const team=(id:string, overrides:Partial<FFBBTeamItem>={}):FFBBTeamItem=>({id,name:'U18 Garçons 1',category:'U18 M1',gender:'M',competition:'Division 3',matchesCount:2,...overrides});
const old=team('phase-one',{customName:'Les Espoirs'});
const next=team('phase-two',{competition:'Division 2 - Phase 2',matchesCount:5});
const grouped=groupFfbbTeams([old,next]);
assert.equal(grouped.length,1);
assert.equal(grouped[0].id,old.id);
assert.equal(grouped[0].customName,'Les Espoirs');
assert.equal(grouped[0].competition,next.competition);
assert.equal(grouped[0].matchesCount,7);
assert.deepEqual(grouped[0].engagementIds,['phase-one','phase-two']);
assert.deepEqual(groupFfbbTeams(grouped),grouped,'Reopening must not inflate counts');
assert.equal(groupFfbbTeams([next],[old])[0].id,old.id);
assert.equal(groupFfbbTeams([next],[old])[0].customName,old.customName);
assert.equal(groupFfbbTeams([next],[old],{'phase-one':'Nom choisi'})[0].customName,'Nom choisi');
assert.equal(groupFfbbTeams([old,old,next])[0].matchesCount,7);
assert.equal(groupFfbbTeams([old,team('squad-two',{category:'U18 M2'})]).length,2);
assert.equal(groupFfbbTeams([old,team('girls',{category:'U18 F1',gender:'F'})]).length,2);
assert.equal(groupFfbbTeams([old,team('u15',{category:'U15 M1'})]).length,2);
assert.equal(groupFfbbTeams([team('a',{season:'2025-2026'}),team('b',{season:'2026-2027'})]).length,2);
assert.equal(groupFfbbTeams([team('unknown1',{category:'Équipe 1'}),team('unknown2',{category:'Équipe 1'})]).length,2);
assert.equal(groupFfbbTeams([next,old])[0].competition,next.competition);
assert.equal(groupFfbbTeams([old,next],[],{'U18 M1':'Nom catégorie'})[0].customName,'Nom catégorie');
assert.equal(old.customName,'Les Espoirs');
assert.equal(old.engagementIds,undefined,'Do not mutate saved input');
console.log('FFBB phases: stable squad, custom names, engagement IDs, counts, separate squads/genders/seasons OK');
